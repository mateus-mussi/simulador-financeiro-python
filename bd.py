# Protótipo didático: os valores ficam APENAS em memória e são apagados ao reiniciar.
_lancamentos = {}

_RECEITAS = {'salario', 'aluguel', 'pensao', 'horas_extra', 'decimo_terceiro', 'ferias', 'rendimentos', 'outros_receitas'}
_INVESTIMENTOS = {'acoes', 'tesouro_direto', 'renda_fixa', 'previdencia_privada', 'outros_investimentos'}


def salvar_no_bd(dados_receitas):
    """Atualiza lançamentos recebidos do formulário (sem banco de dados real)."""
    global _lancamentos
    _lancamentos = dict(dados_receitas)


def obter_dados():
    """Consolida valores enviados por categoria, sem armazenar dados pessoais."""
    resultados = {'RECEITAS': {}, 'DESPESAS FIXAS': {}}
    for chave, texto in _lancamentos.items():
        # Entradas em formato categoria_mes, como salario_jan.
        try:
            categoria, _mes = chave.rsplit('_', 1)
            valor = float(str(texto).strip().replace('.', '').replace(',', '.')) if ',' in str(texto) else float(texto or 0)
        except (ValueError, TypeError):
            continue
        if categoria in _INVESTIMENTOS:
            continue  # investimentos não são despesas
        grupo = 'RECEITAS' if categoria in _RECEITAS else 'DESPESAS FIXAS'
        resultados[grupo][categoria] = resultados[grupo].get(categoria, 0.0) + valor
    return resultados